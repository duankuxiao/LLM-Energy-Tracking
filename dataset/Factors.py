CARBON_FACTOR_YEAR_START = 2017
CARBON_FACTOR_YEAR_END = 2030
CARBON_FACTORS = {"CP": CF_CP, "NDC": CF_NDC, "NZ": CF_NZ}


def _validate_carbon_factor_data():
    expected_count = CARBON_FACTOR_YEAR_END - CARBON_FACTOR_YEAR_START + 1
    reference_countries = set(CF_CP)
    for policy, country_factors in CARBON_FACTORS.items():
        if set(country_factors) != reference_countries:
            raise ValueError(
                f"Carbon-factor countries for {policy} do not match CP."
            )
        invalid_lengths = {
            country: len(values)
            for country, values in country_factors.items()
            if len(values) != expected_count
        }
        if invalid_lengths:
            raise ValueError(
                f"Carbon-factor series for {policy} must contain "
                f"{expected_count} values for "
                f"{CARBON_FACTOR_YEAR_START}-{CARBON_FACTOR_YEAR_END}; "
                f"got {invalid_lengths}."
            )

def get_carbon_factor(policy: str, country: str, year: int) -> float:
    """Return one annual carbon factor using its actual calendar year."""
    if policy not in CARBON_FACTORS:
        raise ValueError(
            f"Unknown carbon policy '{policy}'. Allowed: {list(CARBON_FACTORS)}"
        )
    if country not in CARBON_FACTORS[policy]:
        raise ValueError(f"Unknown country '{country}' for carbon policy {policy}.")
    if not CARBON_FACTOR_YEAR_START <= year <= CARBON_FACTOR_YEAR_END:
        raise ValueError(
            "Carbon-factor year must be within "
            f"{CARBON_FACTOR_YEAR_START}-{CARBON_FACTOR_YEAR_END}, got {year}."
        )
    return float(
        CARBON_FACTORS[policy][country][year - CARBON_FACTOR_YEAR_START]
    )

